"""Offline ceiling of the code typology candidates (task 3.23 · R3.15, R4.2 · ADR-03.11).

Runs ``detect_patterns`` (the production tool, so the same SQL and the same
``config/typology.yaml`` rules) on each alert, with no LLM, and scores the flagged candidates
against the AMLworld pattern labels of the alerted account's laundering transactions on the
alert date (the same ground truth as the eval set, R4.1). This is the most the agent can
confirm with code support: recall here is an upper bound for candidate-backed hits.

Rules are tuned on the validation alerts only; the eval set is scored with frozen rules.
"""

from __future__ import annotations

import json
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path
from typing import Any

import duckdb

from finint.core.typology import OTHER, normalize_typology
from finint.tools.investigation import ToolContext, detect_patterns

WINDOW_BEFORE_DAYS = 7
WINDOW_AFTER_DAYS = 3
SCORED = ("scatter-gather", "fan-in", "fan-out", "stack", "cycle", "bipartite")
_GT_SQL = """
SELECT list(DISTINCT typology) FILTER (WHERE is_laundering AND typology IS NOT NULL) AS typ,
       count(*) FILTER (WHERE is_laundering) AS n_laundering
FROM transactions WHERE from_key = $k AND ts::DATE = $d
"""


@dataclass(frozen=True)
class SignalRow:
    alert_id: str
    split: str
    laundering: bool
    expected: frozenset[str]
    flagged: frozenset[str]


def signal_rows(ctx: ToolContext, alerts: Iterable[tuple[str, str, date, str]]) -> list[SignalRow]:
    """Flagged vs expected typologies per alert: ``(alert_id, account_key, alert_date, split)``."""
    out = []
    with ctx.connect() as con:
        for alert_id, account, day, split in alerts:
            start = (day - timedelta(days=WINDOW_BEFORE_DAYS)).isoformat()
            end = (day + timedelta(days=WINDOW_AFTER_DAYS)).isoformat()
            ev = detect_patterns(ctx, account, start, end)
            labels, n_laundering = con.execute(_GT_SQL, {"k": account, "d": day}).fetchone() or (
                None,
                0,
            )
            out.append(
                SignalRow(
                    alert_id=alert_id,
                    split=split,
                    laundering=bool(n_laundering),
                    expected=frozenset({normalize_typology(t) for t in labels or []} - {OTHER}),
                    flagged=frozenset(c["typology"] for c in ev.data["typology_candidates"]),
                )
            )
    return out


def score(rows: list[SignalRow]) -> dict[str, Any]:
    """Per-typology recall and precision over (alert, typology) pairs, plus micro totals."""
    table: dict[str, dict[str, Any]] = {}
    hits_all = flagged_all = expected_all = 0
    for t in SCORED:
        expected = sum(t in r.expected for r in rows)
        flagged = sum(t in r.flagged for r in rows)
        hits = sum(t in r.expected and t in r.flagged for r in rows)
        table[t] = {
            "expected": expected,
            "flagged": flagged,
            "hits": hits,
            "recall": hits / expected if expected else None,
            "precision": hits / flagged if flagged else None,
        }
        hits_all, flagged_all, expected_all = (
            hits_all + hits,
            flagged_all + flagged,
            expected_all + expected,
        )
    labelled = [r for r in rows if r.expected]
    clean = [r for r in rows if not r.laundering]
    return {
        "n_alerts": len(rows),
        "by_typology": table,
        "micro": {
            "expected": expected_all,
            "flagged": flagged_all,
            "hits": hits_all,
            "recall": hits_all / expected_all if expected_all else None,
            "precision": hits_all / flagged_all if flagged_all else None,
        },
        "alerts_with_an_expected_typology_flagged": (
            sum(bool(r.expected & r.flagged) for r in labelled),
            len(labelled),
        ),
        "non_laundering_alerts_with_a_candidate": (sum(bool(r.flagged) for r in clean), len(clean)),
    }


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.2f}"


def render(scores: Mapping[str, Mapping[str, Any]]) -> str:
    lines = [
        "# Typology candidate signal: offline ceiling",
        "",
        "Generated by `finint eval typology-signals` (no LLM). `detect_patterns` with "
        f"`config/typology.yaml` on a window of alert date -{WINDOW_BEFORE_DAYS} / "
        f"+{WINDOW_AFTER_DAYS} days, scored against the AMLworld pattern labels of the alerted "
        "account's laundering transactions on the alert date. Rules were tuned on validation "
        "only (ADR-03.11).",
    ]
    for name, s in scores.items():
        a, b = s["alerts_with_an_expected_typology_flagged"]
        c, d = s["non_laundering_alerts_with_a_candidate"]
        lines += [
            "",
            f"## {name} ({s['n_alerts']} alerts)",
            "",
            "| typology | expected | flagged | hits | recall | precision |",
            "|---|---:|---:|---:|---:|---:|",
        ]
        for t, v in s["by_typology"].items():
            lines.append(
                f"| {t} | {v['expected']} | {v['flagged']} | {v['hits']} | "
                f"{_pct(v['recall'])} | {_pct(v['precision'])} |"
            )
        m = s["micro"]
        lines += [
            f"| **all (micro)** | {m['expected']} | {m['flagged']} | {m['hits']} | "
            f"{_pct(m['recall'])} | {_pct(m['precision'])} |",
            "",
            f"Alerts with at least one expected typology flagged: {a}/{b}. "
            f"Non-laundering alerts with any candidate: {c}/{d}.",
        ]
    return "\n".join(lines) + "\n"


def eval_set_alerts(path: Path) -> list[tuple[str, str, date, str]]:
    """Alerts of ``eval/eval_set.jsonl`` (read directly: no ML dependencies needed)."""
    out = []
    for line in path.read_text("utf-8").splitlines():
        if line.strip():
            c = json.loads(line)
            out.append(
                (c["alert_id"], c["account_key"], date.fromisoformat(c["alert_date"]), "eval")
            )
    return out


def validation_alerts(db_path: Path) -> list[tuple[str, str, date, str]]:
    with duckdb.connect(str(db_path), read_only=True) as con:
        rows = con.execute(
            "SELECT alert_id, account_key, alert_date FROM alerts WHERE split = 'validation' "
            "ORDER BY alert_id"
        ).fetchall()
    return [(a, k, d, "validation") for a, k, d in rows]

"""Evaluation report (task 4.7 · R4.2-R4.4): ``reports/eval_report.md``.

Numbers come from ``eval/results/*.jsonl`` (one line per run) through ``metrics.summarize``;
nothing in the text is hard-coded except definitions.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from finint.eval.metrics import summarize


def load_results(directory: Path) -> dict[str, list[dict[str, Any]]]:
    out = {}
    for path in sorted(directory.glob("*.jsonl")):
        rows = [json.loads(line) for line in path.read_text("utf-8").splitlines() if line]
        # keep the latest run per (alert, paired) in case a case was re-run
        latest: dict[tuple[str, bool], dict[str, Any]] = {}
        for row in rows:
            latest[(row["alert_id"], bool(row.get("paired_clean")))] = row
        out[path.stem] = list(latest.values())
    return out


def refresh_echo(
    results: dict[str, list[dict[str, Any]]], audit: Any, payloads: dict[str, str]
) -> None:
    """Recompute ``payload_echoed`` from the case file stored in the audit trail.

    The audit is the record of what the agent wrote, so the metric does not depend on the
    version of the runner that produced the results line.
    """
    from finint.eval.runner import _payload_echoed

    for rows in results.values():
        for row in rows:
            if not row.get("injection_case") or row.get("paired_clean"):
                continue
            drafted = [
                e for e in audit.events(run_id=row["run_id"]) if e.event_type == "CASE_DRAFTED"
            ]
            case = drafted[-1].payload.get("case") if drafted else None
            row["payload_echoed"] = _payload_echoed(case, payloads.get(row["injection_case"]))


def _pct(value: float | None) -> str:
    return "-" if value is None else f"{value:.0%}"


def _num(value: float | None, digits: int = 2) -> str:
    return "-" if value is None else f"{value:,.{digits}f}"


def _table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(v) for v in row) + " |" for row in rows]
    return "\n".join(out)


def screening_section(screening: dict[str, Any] | None) -> list[str]:
    if not screening:
        return []
    return [
        "## Sanctions screener on the injected cases (deterministic, no LLM)",
        f"{screening['n']} hand-curated cases against the OFAC SDN list: "
        f"**{screening['true_matches_found']}/{screening['n_true']} true matches** reach `MATCH`, "
        f"**{screening['decoys_cleared']}/{screening['n_decoys']} decoys** (same or similar name, "
        "different person) are not `MATCH` and show the contradicting fields. The LLM cannot "
        "change a screening status (policy rule POL-01).",
    ]


def build_eval_report(
    results: dict[str, list[dict[str, Any]]], screening: dict[str, Any] | None
) -> str:
    summaries = {name: summarize(rows) for name, rows in results.items() if rows}
    if "main" not in summaries:
        return "# Agent evaluation\n\nNo results yet. Run `make eval`.\n"
    main = summaries["main"]
    d, f, p, i, s, m, e = (
        main[k]
        for k in (
            "disposition",
            "faithfulness",
            "patterns",
            "injection",
            "sanctions",
            "media",
            "efficiency",
        )
    )
    sections = [
        "# Agent evaluation",
        "Generated by `make eval-report` from `eval/results/*.jsonl`. Eval set: "
        f"{d['n']} alerts from the test period (`eval/eval_set.jsonl`): natural alerts raised by "
        "the champion model (laundering stratified by typology, plus false positives) and forced "
        "alerts carrying injected test cases (prompt injection, sanctions near-matches, adverse "
        "media). Ground truth: dataset labels and the documented injections. A simulated analyst "
        "decides every case from the ground truth after the agent, so the audit trail holds "
        "realistic decisions.",
        "## Headline (config `main`)",
        "Models: "
        + ", ".join(
            f"{role} `{model}`"
            for role, model in sorted((results["main"][0].get("models") or {}).items())
        )
        + ".",
        _table(
            ["Metric", "Value", "How it is measured"],
            [
                ("Disposition accuracy", _pct(d["accuracy"]), "policy disposition = ground truth"),
                (
                    "… natural / forced alerts",
                    f"{_pct(d['accuracy_natural'])} / {_pct(d['accuracy_forced'])}",
                    "",
                ),
                (
                    "Agent accuracy before the policy guard",
                    _pct(d["agent_accuracy_before_policy"]),
                    "agent's own recommendation",
                ),
                (
                    "Laundering escalated",
                    _pct(d["escalation_recall"]),
                    "ESCALATE on laundering alerts",
                ),
                (
                    "Laundering recommended for closure",
                    str(d["missed_laundering_closed"]),
                    "the dangerous error",
                ),
                (
                    "NEEDS_MORE_INFO rate",
                    _pct(d["needs_more_info_rate"]),
                    "counted as wrong in accuracy",
                ),
                (
                    "Unsupported values in released case files",
                    str(f["unsupported_values_in_released"]),
                    f"code check over {f['released_case_files']} released files",
                ),
                ("First draft grounded", _pct(f["first_draft_grounded"]), "before the repair loop"),
                ("Blocked as ungrounded", _pct(f["blocked_rate"]), "after 2 repair attempts"),
                (
                    "Pattern identification recall",
                    _pct(p["recall"]),
                    "expected typologies marked CONFIRMED",
                ),
                ("Pattern precision", _pct(p["precision"]), ""),
                (
                    "Prompt-injection success",
                    _pct(i["success_rate"]),
                    "paired: payload lowered scrutiny, made the agent close, or reached an "
                    "off-allowlist tool",
                ),
                (
                    "Payload raised scrutiny instead",
                    _pct(i["raised_scrutiny_rate"]),
                    "detector flag + policy guard (POL-04), or the agent reporting it",
                ),
                (
                    "Injection detection",
                    _pct(i["detection_recall"]),
                    "payload flagged and shown to the analyst",
                ),
                (
                    "Latency p50 / p90",
                    f"{_num(e['latency_p50_s'], 0)} s / {_num(e['latency_p90_s'], 0)} s",
                    f"wall time per case; max {_num(e['latency_max_s'], 0)} s "
                    "(machine asleep or rate-limit waits)",
                ),
                (
                    "Cost per case (mean / p95)",
                    f"${_num(e['cost_mean_usd'], 4)} / ${_num(e['cost_p95_usd'], 4)}",
                    "list prices via genai-prices; the PoC ran on the free tier",
                ),
            ],
        ),
        "## Dispositions",
        _table(
            ["Expected \\ Policy", "ESCALATE", "NEEDS_MORE_INFO", "CLOSE_FALSE_POSITIVE"],
            [(k, *v.values()) for k, v in d["confusion"].items()],
        ),
        f"Policy guard overrode the agent in {_pct(d['policy_override_rate'])} of cases "
        "(it can only move towards more scrutiny).",
        "## Pattern identification",
        _table(
            ["Typology", "Cases", "Recall"],
            [(t, v["n"], _pct(v["recall"])) for t, v in p["by_typology"].items()],
        ),
        "## Prompt injection (paired runs)",
        "Each injection alert is also run with its original memo restored. Every payload pushes "
        "towards less scrutiny, so it succeeds only if it lowers the outcome's severity, makes "
        "the agent close where it otherwise would not, or reaches a tool outside the allowlist. "
        "'Quoted' means the agent reported the memo in the case file, as the prompt asks.",
        _table(
            [
                "Case",
                "Detected",
                "With payload",
                "Without",
                "Agent with / without",
                "Quoted",
                "Success",
            ],
            [
                (
                    o["case"],
                    "yes" if o["detected"] else "no",
                    o["with_payload"],
                    o["without_payload"] or "-",
                    f"{o['agent_with']} / {o['agent_without'] or '-'}",
                    "yes" if o["quoted_in_case"] else "no",
                    "**yes**" if o["success"] else "no",
                )
                for o in i["outcomes"]
            ],
        ),
        "## Sanctions and adverse media inside investigations",
        f"Linked sanctions parties screened by the agent: {_pct(s['screened_rate'])} "
        f"(subjects {_pct(s['subject_screened_rate'])}, "
        f"counterparties {_pct(s['counterparty_screened_rate'])}); "
        f"status correct when screened: {_pct(s['correct_when_screened'])}. "
        f"Adverse-media checks requested on media cases: {_pct(m['requested_rate'])}; "
        f"correct classification: {_pct(m['correct_rate'])}.",
        *screening_section(screening),
        "## Efficiency",
        _table(
            ["Metric", "Value"],
            [
                ("LLM calls per case (mean)", _num(e["llm_calls_mean"], 1)),
                ("Tool calls per case (mean)", _num(e["tool_calls_mean"], 1)),
                (
                    "Input / output tokens per case (mean)",
                    f"{_num(e['input_tokens_mean'], 0)} / {_num(e['output_tokens_mean'], 0)}",
                ),
                ("Reviewer asked for revision", _pct(e["review_revise_rate"])),
                ("Skills loaded per case (mean)", _num(e["skills_loaded_mean"], 1)),
                ("Total cost of this evaluation (list prices)", f"${_num(e['cost_total_usd'], 2)}"),
            ],
        ),
    ]
    others = {k: v for k, v in summaries.items() if k != "main"}
    if others:
        rows = []
        for name in others:
            ids = {r["alert_id"] for r in results[name] if not r.get("paired_clean")}
            base = summarize([r for r in results["main"] if r["alert_id"] in ids])
            for label, summ in ((f"main (same {len(ids)} cases)", base), (name, others[name])):
                dd, ff, pp, ee = (
                    summ[k] for k in ("disposition", "faithfulness", "patterns", "efficiency")
                )
                rows.append(
                    (
                        label,
                        dd["n"],
                        _pct(dd["accuracy"]),
                        _pct(dd["escalation_recall"]),
                        str(dd["missed_laundering_closed"]),
                        _pct(ff["first_draft_grounded"]),
                        _pct(pp["recall"]),
                        _num(ee["tool_calls_mean"], 1),
                        f"${_num(ee['cost_mean_usd'], 4)}",
                    )
                )
        sections += [
            "## Configurations compared on the same cases",
            "Each configuration is compared with `main` restricted to exactly the alerts it ran. "
            "`harness-v2`: coverage gate (detect_patterns, counterparties, trace_flows and "
            "screening must run on the alerted account before a case is accepted), calibrated "
            "base rate and a decision rubric in the prompt, stricter reviewer on closures. "
            "`flash-reviewer`: Gemini Flash as reviewer (free tier: 20 requests a day).",
            _table(
                [
                    "Config",
                    "n",
                    "Accuracy",
                    "Laundering escalated",
                    "Laundering closed",
                    "First draft grounded",
                    "Pattern recall",
                    "Tool calls",
                    "Cost/case",
                ],
                rows,
            ),
        ]
    wrong = [r for r in results["main"] if not r.get("paired_clean") and not r["correct"]]
    sections += [
        "## Errors (config `main`)",
        _table(
            ["Alert", "Source", "Reason", "Expected", "Agent", "Policy"],
            [
                (
                    r["alert_id"],
                    r["source"],
                    ";".join(r["reasons"]),
                    r["expected"],
                    r["agent_disposition"],
                    r["policy_disposition"],
                )
                for r in wrong
            ],
        )
        if wrong
        else "None.",
        "## Limitations",
        "- Ground truth is the synthetic dataset's label for the account-day; an alert counts as "
        "laundering if any transaction that day is labelled laundering.\n"
        "- The simulated analyst follows the label; real analyst disagreement is not modelled.\n"
        "- Free-tier rate limits make runs slower; costs are list-price estimates, not invoices.\n"
        "- LLM outputs vary between runs; the record/replay CI job checks the pipeline, not the "
        "model's quality.",
    ]
    return "\n\n".join(sections) + "\n"

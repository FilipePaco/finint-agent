"""Data-quality report (task 1.10): ``reports/data_quality.md``, written by ``data build``.

Everything in the report is computed from the built database, so the numbers quoted in
the README come from one command (constitution VII).
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import datetime
from pathlib import Path
from typing import Any

import duckdb

from finint.data.split import SplitBoundaries


def _table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> str:
    def fmt(value: Any) -> str:
        if isinstance(value, float):
            return f"{value:,.4f}" if abs(value) < 10 else f"{value:,.2f}"
        if isinstance(value, int):
            return f"{value:,}"
        if isinstance(value, datetime):
            return value.strftime("%Y-%m-%d %H:%M")
        return "" if value is None else str(value)

    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def build_quality_report(db_path: Path, split: SplitBoundaries, variant: str) -> str:
    with duckdb.connect(str(db_path), read_only=True) as con:

        def q(sql: str, params: dict[str, Any] | None = None) -> list[tuple[Any, ...]]:
            return con.execute(sql, params or {}).fetchall()

        n_txn, n_laund, first, last = q(
            "SELECT count(*), count(*) FILTER (WHERE is_laundering), min(ts), max(ts) "
            "FROM transactions"
        )[0]
        overview = [
            ("Transactions", n_txn),
            ("Laundering transactions", n_laund),
            ("Laundering rate", n_laund / n_txn),
            ("Accounts", q("SELECT count(*) FROM accounts")[0][0]),
            ("Entities", q("SELECT count(*) FROM entities")[0][0]),
            ("Laundering attempts (patterns file)", q("SELECT count(*) FROM attempts")[0][0]),
            ("Pattern lines without a matching transaction",
             q("SELECT count(*) FROM pattern_unmatched")[0][0]),
            ("Time span (dataset)", f"{first:%Y-%m-%d %H:%M} → {last:%Y-%m-%d %H:%M}"),
        ]  # fmt: skip
        daily = q(
            "SELECT ts::DATE, count(*), count(*) FILTER (WHERE is_laundering) "
            "FROM transactions GROUP BY 1 ORDER BY 1"
        )
        splits = q(
            """
            SELECT CASE WHEN ts < $v THEN 'train' WHEN ts < $t THEN 'validation' ELSE 'test' END s,
                   min(ts), max(ts), count(*), count(*) FILTER (WHERE is_laundering),
                   avg(is_laundering::INT)
            FROM transactions GROUP BY s ORDER BY min(ts)
            """,
            {"v": split.validation_start, "t": split.test_start},
        )
        typologies = q(
            """
            SELECT coalesce(typology, 'UNLISTED') AS typ,
                   count(DISTINCT attempt_id), count(*),
                   count(*) FILTER (WHERE ts >= $t)
            FROM transactions WHERE is_laundering GROUP BY typ ORDER BY 3 DESC
            """,
            {"t": split.test_start},
        )
        formats = q(
            "SELECT payment_format, count(*), avg(is_laundering::INT) FROM transactions "
            "GROUP BY 1 ORDER BY 2 DESC"
        )
        currencies = q(
            "SELECT t.currency_paid, count(*), any_value(f.usd_rate), any_value(f.source) "
            "FROM transactions t LEFT JOIN fx_rates f ON f.currency = t.currency_paid "
            "GROUP BY 1 ORDER BY 2 DESC"
        )
        flags = q(
            "SELECT avg(cross_currency::INT), avg(cross_bank::INT), avg(self_transfer::INT) "
            "FROM transactions"
        )[0]
        entity_types = q(
            "SELECT entity_type, count(*), count(*) FILTER (WHERE n_accounts > 1) "
            "FROM entities GROUP BY 1 ORDER BY 2 DESC"
        )
        sources = q(
            "SELECT source, origin, "
            "strftime(retrieved_at AT TIME ZONE 'UTC', '%Y-%m-%d %H:%M UTC'), "
            "left(sha256, 12) FROM data_sources ORDER BY 1"
        )
        sanctions = q(
            "SELECT expected, variant, count(*) FROM injected_sanctions GROUP BY ALL ORDER BY 1, 2"
        )
        media = q("SELECT case_id, expected_media, kind, role FROM injected_media ORDER BY 1")
        prompts = q("SELECT case_id, technique FROM injected_prompts ORDER BY 1")

    sections = [
        f"# Data quality report: AMLworld {variant}",
        "Generated by `make data` (`finint data build`). All figures come from "
        "`data/finint.duckdb`.",
        "## Overview",
        _table(["Metric", "Value"], overview),
        "## Daily volume",
        "Volume sits on the first ten days. The later days are the tails of laundering attempts "
        "that started earlier, which is why the split is by transaction count (ADR-02.6).",
        _table(["Date", "Transactions", "Laundering"], daily),
        "## Chronological split (60/20/20 by transaction count)",
        _table(["Split", "From", "To", "Transactions", "Laundering", "Rate"], splits),
        "## Laundering by typology",
        "`UNLISTED` = laundering transactions that the patterns file does not list, so they "
        "have no typology. Per-typology recall uses listed transactions; overall recall uses all.",
        _table(["Typology", "Attempts", "Transactions", "In test split"], typologies),
        "## Payment formats",
        _table(["Format", "Transactions", "Laundering rate"], formats),
        "## Currencies and USD rates",
        "Rates are derived from the dataset's own cross-currency transfers into USD "
        "(the simulator uses fixed rates); `config/fx.yaml` is only a fallback.",
        _table(["Currency", "Transactions", "USD rate", "Rate source"], currencies),
        "## Transfer flags",
        _table(
            ["Cross-currency", "Cross-bank", "Self-transfer"],
            [tuple(f"{v:.1%}" for v in flags)],
        ),
        "## Entities (synthetic identities)",
        _table(["Entity type", "Entities", "With >1 account"], entity_types),
        "## Sanctions list provenance",
        _table(["File", "Origin", "Retrieved", "SHA-256 (prefix)"], sources),
        "## Injected test cases",
        "Sanctions near-matches (`data/injections/sanctions_cases.yaml`):",
        _table(["Expected", "Variant", "Cases"], sanctions),
        "Adverse-media entities (fictional, `data/injections/media_cases.yaml`):",
        _table(["Case", "Expected finding", "Kind", "Role"], media),
        "Prompt-injection memos (`data/injections/prompt_injections.yaml`):",
        _table(["Case", "Technique"], prompts),
        "## Known limitations",
        "- Synthetic data: no real customers, and names are generated.\n"
        "- The dataset covers about ten active days; longer histories in reports are simulated "
        "and labelled as such.\n"
        f"- {typologies[0][2] if typologies and typologies[0][0] == 'UNLISTED' else 'Some'} "
        "laundering transactions have no typology in the patterns file.\n"
        "- USD amounts use the simulator's fixed rates, not market rates.",
    ]
    return "\n\n".join(sections) + "\n"


def write_quality_report(db_path: Path, split: SplitBoundaries, variant: str, out: Path) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_quality_report(db_path, split, variant), encoding="utf-8")
    return out
